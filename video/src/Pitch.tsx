import React, { useEffect, useState } from "react";
import { AbsoluteFill, Audio, continueRender, delayRender, getStaticFiles, Series, staticFile } from "remotion";

import { fontsReady } from "./fonts";
import { Next, Prize } from "./scenes/Close";
import { HowItWorks, Idea, LiveRun, Result } from "./scenes/Demo";
import { Question, Stakes, Twist } from "./scenes/Opening";
import { C, SCENES, SceneId } from "./theme";

const COMPONENTS: Record<SceneId, React.FC> = {
  question: Question,
  stakes: Stakes,
  twist: Twist,
  idea: Idea,
  how: HowItWorks,
  live: LiveRun,
  result: Result,
  prize: Prize,
  next: Next,
};

// Voiceover is generated by scripts/voiceover.py and not committed; render silently without it.
const HAS_VOICEOVER = getStaticFiles().some((f) => f.name === "audio/voiceover.wav");

export const Pitch: React.FC = () => {
  const [handle] = useState(() => delayRender("Loading fonts"));
  useEffect(() => {
    fontsReady
      .then(() => continueRender(handle))
      .catch((e) => {
        console.error(e);
        continueRender(handle);
      });
  }, [handle]);
  return (
    <AbsoluteFill style={{ background: C.paper }}>
      <Series>
        {SCENES.map((s) => {
          const Comp = COMPONENTS[s.id];
          return (
            <Series.Sequence key={s.id} durationInFrames={s.frames}>
              <Comp />
            </Series.Sequence>
          );
        })}
      </Series>
      {HAS_VOICEOVER ? <Audio src={staticFile("audio/voiceover.wav")} /> : null}
    </AbsoluteFill>
  );
};
